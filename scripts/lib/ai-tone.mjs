// 去 AI 味的規則表 —— **單一真實來源**。
//
// 為什麼抽出來（2026-08-27）：check-content.mjs 只掃 `src/**/*.md(x)`，
// 而這個站的文案全部在 `.astro`、`.js`、`.json` 裡，**一個 .md 都沒有** ——
// 那道守門從上線起掃了 0 個檔，每次 build 都印「無變動的 .md/.mdx 內容檔」，
// 看起來是綠的，其實一句話都沒檢查過。（同型病灶：index-ping 回報「成功 30／失敗 0」
// 卻不含新頁——**綠燈不等於檢查過，要驗的是它到底掃了什麼**。）
//
// 修法是加一支掃 `dist/**/*.html` 的 check-copy.mjs：文案散在三種檔案裡，
// 掃產物才全涵蓋，而且那正是使用者看到的字。
// 規則若各寫一份就會漂移，所以兩支共用這一份。

